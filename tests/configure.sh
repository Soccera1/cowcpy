#!/bin/sh
set -eu
output=$1
backend=$2
backing=$3
remap=$4
allow_disk=$5
run=$6
signal_mode=$7
min_pages=$8
mutable=$9
work=$(mktemp -d "${output%/*}/configure.XXXXXX")
trap 'rm -rf "$work"' EXIT HUP INT TERM
libs=

compile() {
    $CC $CPPFLAGS $CFLAGS "$work/probe.c" $LDFLAGS $libs -pthread -o "$work/probe"
}
cat >"$work/probe.c" <<'EOF'
#define _GNU_SOURCE
#include <sys/mman.h>
#include <unistd.h>
int main(void) { int fd = memfd_create("cowcpy-probe", MFD_CLOEXEC); if (fd < 0) return 1; close(fd); return 0; }
EOF
memfd=0
if compile >"$work/log" 2>&1; then memfd=1; fi
cat >"$work/probe.c" <<'EOF'
#define _POSIX_C_SOURCE 200809L
#include <sys/mman.h>
#include <fcntl.h>
int main(void) { int (*open_object)(const char *, int, mode_t) = shm_open; return open_object == 0; }
EOF
shm=0
if compile >"$work/log" 2>&1; then
    shm=1
else
    libs=-lrt
    if compile >"$work/log" 2>&1; then shm=1; else libs=; fi
fi
cat >"$work/probe.c" <<'EOF'
#include <mach/mach.h>
#include <mach/mach_vm.h>
int main(void) { return mach_vm_copy(mach_task_self(), 0, 0, 0) != KERN_SUCCESS; }
EOF
mach=0
if compile >"$work/log" 2>&1; then mach=1; fi
case "$backend" in
    auto) backend_id=0;; mapped) backend_id=1;; mach) backend_id=2;;
    signal) backend_id=3;; eager) backend_id=4;;
    *) echo 'BACKEND must be auto, mapped, mach, signal, or eager' >&2; exit 2;;
esac
case "$backing" in
    auto) backing_id=0;; memfd) backing_id=1;; shm) backing_id=2;;
    tmp) backing_id=3;; anonymous) backing_id=4;;
    *) echo 'BACKING must be auto, memfd, shm, tmp, or anonymous' >&2; exit 2;;
esac
case "$remap" in auto|yes|1) fixed=1;; no|0) fixed=0;; *) echo 'REMAP must be auto, yes, or no' >&2; exit 2;; esac
case "$allow_disk" in 0|1) ;; *) echo 'ALLOW_DISK must be 0 or 1' >&2; exit 2;; esac
case "$min_pages" in ''|*[!0-9]*) echo 'MIN_COPY_PAGES must be an unsigned integer' >&2; exit 2;; esac
case "$mutable" in 0|1) ;; *) echo 'MUTABLE_SNAPSHOTS must be 0 or 1' >&2; exit 2;; esac
case "$signal_mode" in auto|alias) direct=0;; single) direct=1;; *) echo 'SIGNAL_MODE must be auto, alias, or single' >&2; exit 2;; esac
lazy=1
if [ "$remap" = auto ]; then
    if [ "$run" = 0 ]; then
        fixed=0
        echo 'cowcpy: cross-compilation disables untested fixed remapping; override with REMAP=yes' >&2
    elif $CC $CPPFLAGS $CFLAGS -Iinclude -Isrc -DCOWCPY_TEST_VM \
        -DCOW_BACKEND_REQUEST=1 -DCOW_BACKING_REQUEST="$backing_id" \
        -DCOW_ALLOW_DISK="$allow_disk" -DCOW_HAVE_MEMFD="$memfd" \
        -DCOW_HAVE_SHM="$shm" -DCOW_HAVE_MACH=0 \
        src/cowcpy.c src/signal.c tests/probe_mapped.c \
        $LDFLAGS $libs -pthread -o "$work/mapped" >"$work/log" 2>&1 &&
        "$work/mapped" >>"$work/log" 2>&1; then
        echo 'cowcpy: private-mapping publication and write-isolation probe passed' >&2
    else
        fixed=0
        echo 'cowcpy: fixed-remapping probe unavailable; copies use eager fallback' >&2
    fi
fi
if [ "$backend" = signal ] && [ "$signal_mode" = auto ]; then
    if [ "$run" = 0 ]; then
        lazy=0
        echo 'cowcpy: untested signal backend disabled during cross-compilation; use SIGNAL_MODE=alias to opt in' >&2
    else
        if $CC $CPPFLAGS $CFLAGS -Iinclude -Isrc -DCOWCPY_FORCE_SIGNAL \
            -DCOWCPY_TEST_HOOKS -DCOWCPY_SIGNAL_DIRECT=0 -DCOW_MIN_PAGES=0 \
            -DCOW_HAVE_MEMFD="$memfd" -DCOW_HAVE_SHM="$shm" \
            src/cowcpy.c src/signal.c tests/probe_publication.c \
            $LDFLAGS $libs -pthread -o "$work/signal" >"$work/log" 2>&1 &&
            "$work/signal" >>"$work/log" 2>&1; then
            echo 'cowcpy: opt-in synchronized signal probe passed (host extensions required)' >&2
        else
            lazy=0
            direct=1
            echo 'cowcpy: signal probe failed; selecting eager fallback' >&2
            cat "$work/log" >&2
        fi
    fi
fi
{
    echo '/* Generated by make. Runtime backing failures also fall back safely. */'
    echo "#define COW_HAVE_MEMFD $memfd"
    echo "#define COW_HAVE_SHM $shm"
    echo "#define COW_HAVE_MACH $mach"
    echo "#define COW_BACKEND_REQUEST $backend_id"
    echo "#define COW_BACKING_REQUEST $backing_id"
    echo "#define COW_FIXED_REMAP $fixed"
    echo "#define COW_ALLOW_DISK $allow_disk"
    echo "#define COW_MIN_PAGES $min_pages"
    echo "#define COW_MUTABLE_SNAPSHOTS $mutable"
    echo '#ifndef COWCPY_SIGNAL_DIRECT'
    echo "#define COWCPY_SIGNAL_DIRECT $direct"
    echo '#endif'
    echo '#ifndef COWCPY_SIGNAL_LAZY'
    echo "#define COWCPY_SIGNAL_LAZY $lazy"
    echo '#endif'
} >"$work/config.h"
printf '%s\n' "$libs" >"$work/libs"
if [ "$mach" = 1 ]; then
    echo '-dynamiclib -Wl,-install_name,@rpath/libcowcpy.so' >"$work/sharedflags"
else
    echo '-shared' >"$work/sharedflags"
fi
if ! cmp -s "$work/config.h" "$output"; then cp "$work/config.h" "$output"; fi
if ! cmp -s "$work/libs" "${output%/*}/cowcpy.libs"; then cp "$work/libs" "${output%/*}/cowcpy.libs"; fi
if ! cmp -s "$work/sharedflags" "${output%/*}/cowcpy.sharedflags"; then cp "$work/sharedflags" "${output%/*}/cowcpy.sharedflags"; fi
echo "cowcpy: backend=$backend memfd=$memfd shm=$shm mach=$mach remap=$fixed disk=$allow_disk" >&2
